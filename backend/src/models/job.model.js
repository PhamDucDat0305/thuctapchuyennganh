module.exports = (sequelize, DataTypes) => sequelize.define('Job', {
  id: { type: DataTypes.BIGINT, primaryKey: true, autoIncrement: true, field: 'id' },
  companyId: { type: DataTypes.BIGINT, allowNull: false, field: 'company_id' },
  recruiterId: { type: DataTypes.BIGINT, allowNull: false, field: 'recruiter_id' },
  title: { type: DataTypes.STRING(200), allowNull: false, field: 'title' },
  description: { type: DataTypes.TEXT, allowNull: false, field: 'description' },
  requirements: { type: DataTypes.TEXT, allowNull: true, field: 'requirements' },
  benefits: { type: DataTypes.TEXT, allowNull: true, field: 'benefits' },
  category: { type: DataTypes.STRING(100), allowNull: true, field: 'category' },
  location: { type: DataTypes.STRING(200), allowNull: true, field: 'location' },
  salaryDisplay: { type: DataTypes.STRING(100), allowNull: true, field: 'salary_display' },
  salaryMin: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'salary_min' },
  salaryMax: { type: DataTypes.DECIMAL(12, 2), allowNull: true, field: 'salary_max' },
  currency: { type: DataTypes.CHAR(3), allowNull: false, field: 'currency' },
  jobType: { type: DataTypes.STRING(30), allowNull: true, field: 'job_type' },
  experience: { type: DataTypes.STRING(50), allowNull: true, field: 'experience' },
  status: { type: DataTypes.STRING(20), allowNull: false, field: 'status' },
  expiresAt: { type: DataTypes.DATE, allowNull: true, field: 'expires_at' },
  views: { type: DataTypes.INTEGER, allowNull: false, field: 'views' },
  adminVisibility: { type: DataTypes.STRING(20), allowNull: false, field: 'admin_visibility' },
  createdAt: { type: DataTypes.DATE, allowNull: false, field: 'created_at' },
  updatedAt: { type: DataTypes.DATE, allowNull: false, field: 'updated_at' },
}, { tableName: 'jobs' });
